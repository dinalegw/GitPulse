import { Sandbox } from '@vercel/sandbox';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const GENERATED_PATH = resolve(process.cwd(), 'lib/generated/playground-runtime.ts');
const REGION = process.env.PLAYGROUND_SANDBOX_REGION || 'iad1';
const SCHEMA_VERSION = 1;
const GO_VERSION = '1.26.3';
const SNAPSHOT_EXPIRATION_MS = 7 * 24 * 60 * 60 * 1000;
const SCRATCH_DIR = '/vercel/sandbox/scratch-repo';
const SOURCE_DIR = '/vercel/sandbox/gitpulse-src';
const BIN_DIR = '/vercel/sandbox/bin';
const GITPULSE_BIN = BIN_DIR + '/gitpulse';
const SANDBOX_HOME = '/vercel/sandbox/home';
const FAKE_ORIGIN = '/vercel/sandbox/fake-origin.git';
const GO_ROOT = '/vercel/sandbox/go';
const MARKER_PATH = '/vercel/sandbox/gitpulse-runtime.json';

const GO_SHA256 = {
  amd64: '2b2cfc7148493da5e73981bffbf3353af381d5f93e789c82c79aff64962eb556',
  arm64: '9d89a3ea57d141c2b22d70083f2c8459ba3890f2d9e818e7e933b75614936565',
};

const SAFE_ENV = {
  HOME: SANDBOX_HOME,
  GIT_CONFIG_NOSYSTEM: '1',
  GIT_CONFIG_GLOBAL: '/dev/null',
  GIT_TERMINAL_PROMPT: '0',
  GCM_INTERACTIVE: 'Never',
  GH_TOKEN: '',
  GITHUB_TOKEN: '',
  GIT_ASKPASS: '',
};

function validRef(value) {
  return typeof value === 'string' && /^[A-Za-z0-9._/-]{1,100}$/.test(value);
}

function sourceRef() {
  const candidate =
    process.env.VERCEL_GIT_COMMIT_SHA ||
    process.env.GITPULSE_PLAYGROUND_SOURCE_REF ||
    'main';
  return validRef(candidate) ? candidate : 'main';
}

async function writeGenerated(runtime) {
  await mkdir(dirname(GENERATED_PATH), { recursive: true });
  const content = `// Generated by scripts/playground/create-runtime-snapshot.mjs
export const PLAYGROUND_RUNTIME = ${JSON.stringify(runtime, null, 2)} as const;
`;
  await writeFile(GENERATED_PATH, content, 'utf8');
}

async function writeColdFallback(ref, reason) {
  await writeGenerated({
    schemaVersion: SCHEMA_VERSION,
    snapshotId: null,
    sourceCommit: ref === 'main' ? null : ref,
    binarySha256: null,
    region: REGION,
  });
  console.warn(`[playground snapshot] ${reason}; using cold fallback for this build`);
}

async function run(sandbox, cmd, args, options = {}) {
  const result = await sandbox.runCommand({
    cmd,
    args,
    cwd: options.cwd,
    env: options.env,
    sudo: options.sudo,
  });
  const stdout = await result.stdout();
  const stderr = await result.stderr();
  if (result.exitCode !== 0) {
    throw new Error(stderr.trim() || stdout.trim() || `${cmd} failed with exit code ${result.exitCode}`);
  }
  return stdout;
}

async function available(sandbox, cmd, args = ['--version']) {
  try {
    const result = await sandbox.runCommand({ cmd, args, env: SAFE_ENV });
    return result.exitCode === 0;
  } catch {
    return false;
  }
}

async function ensureGo(sandbox) {
  if (await available(sandbox, 'go', ['version'])) return 'go';
  if (!(await available(sandbox, 'node', ['--version']))) {
    throw new Error('snapshot image is missing Node.js');
  }
  if (!(await available(sandbox, 'tar', ['--version']))) {
    throw new Error('snapshot image is missing tar');
  }

  const machine = (await run(sandbox, 'uname', ['-m'], { env: SAFE_ENV })).trim();
  let arch;
  if (machine === 'x86_64' || machine === 'amd64') arch = 'amd64';
  else if (machine === 'aarch64' || machine === 'arm64') arch = 'arm64';
  else throw new Error(`unsupported sandbox architecture: ${machine}`);

  const tarball = `/vercel/sandbox/go${GO_VERSION}.linux-${arch}.tar.gz`;
  const url = `https://go.dev/dl/go${GO_VERSION}.linux-${arch}.tar.gz`;
  const expected = GO_SHA256[arch];
  const downloader = [
    'const fs=require("fs");',
    'const crypto=require("crypto");',
    'const [url,file,expected]=process.argv.slice(-3);',
    '(async()=>{',
    ' const r=await fetch(url);',
    ' if(!r.ok) throw new Error("download failed: HTTP "+r.status);',
    ' const b=Buffer.from(await r.arrayBuffer());',
    ' const actual=crypto.createHash("sha256").update(b).digest("hex");',
    ' if(actual!==expected) throw new Error("Go checksum mismatch: "+actual);',
    ' fs.writeFileSync(file,b);',
    '})().catch(e=>{console.error(e.message||e);process.exit(1)});',
  ].join('');

  await run(sandbox, 'node', ['-e', downloader, url, tarball, expected], { env: SAFE_ENV });
  await run(sandbox, 'rm', ['-rf', GO_ROOT], { env: SAFE_ENV });
  await run(sandbox, 'mkdir', ['-p', GO_ROOT], { env: SAFE_ENV });
  await run(sandbox, 'tar', ['-xzf', tarball, '-C', GO_ROOT, '--strip-components=1'], { env: SAFE_ENV });
  return `${GO_ROOT}/bin/go`;
}

async function prepareSnapshot(sandbox, ref) {
  if (!(await available(sandbox, 'git', ['--version']))) {
    throw new Error('snapshot image is missing git');
  }

  await run(sandbox, 'rm', ['-rf', SCRATCH_DIR, SOURCE_DIR, BIN_DIR, SANDBOX_HOME, FAKE_ORIGIN, GO_ROOT], { env: SAFE_ENV });
  await run(sandbox, 'mkdir', ['-p', SCRATCH_DIR, BIN_DIR, SANDBOX_HOME], { env: SAFE_ENV });

  const goBin = await ensureGo(sandbox);

  await run(sandbox, 'git', ['init', SOURCE_DIR], { env: SAFE_ENV });
  await run(sandbox, 'git', [
    '-c', 'credential.helper=',
    '-c', 'core.askPass=',
    '-C', SOURCE_DIR,
    'remote', 'add', 'origin',
    'https://github.com/dinalegw/GitPulse.git',
  ], { env: SAFE_ENV });
  await run(sandbox, 'git', [
    '-c', 'credential.helper=',
    '-c', 'core.askPass=',
    '-C', SOURCE_DIR,
    'fetch', '--depth', '1', 'origin', ref,
  ], { env: SAFE_ENV });
  await run(sandbox, 'git', ['-C', SOURCE_DIR, 'checkout', '--detach', 'FETCH_HEAD'], { env: SAFE_ENV });
  await run(sandbox, goBin, ['build', '-trimpath', '-o', GITPULSE_BIN, '.'], { cwd: SOURCE_DIR, env: SAFE_ENV });

  await run(sandbox, GITPULSE_BIN, ['version'], { env: SAFE_ENV });

  await run(sandbox, 'git', ['init'], { cwd: SCRATCH_DIR, env: SAFE_ENV });
  await run(sandbox, 'git', ['branch', '-M', 'main'], { cwd: SCRATCH_DIR, env: SAFE_ENV });
  await run(sandbox, 'git', ['config', 'user.email', 'playground@gitpulse.local'], { cwd: SCRATCH_DIR, env: SAFE_ENV });
  await run(sandbox, 'git', ['config', 'user.name', 'GitPulse Playground'], { cwd: SCRATCH_DIR, env: SAFE_ENV });

  await sandbox.writeFiles([{
    path: `${SCRATCH_DIR}/README.md`,
    content: Buffer.from('# Scratch Repository\n', 'utf8'),
  }]);

  await run(sandbox, 'git', ['add', 'README.md'], { cwd: SCRATCH_DIR, env: SAFE_ENV });
  await run(sandbox, 'git', ['commit', '-m', 'Initial commit'], { cwd: SCRATCH_DIR, env: SAFE_ENV });
  await run(sandbox, 'git', ['init', '--bare', FAKE_ORIGIN], { env: SAFE_ENV });
  await run(sandbox, 'git', ['remote', 'add', 'origin', FAKE_ORIGIN], { cwd: SCRATCH_DIR, env: SAFE_ENV });
  await run(sandbox, 'git', ['push', '-u', 'origin', 'main'], { cwd: SCRATCH_DIR, env: SAFE_ENV });

  const configDir = `${SANDBOX_HOME}/.gitpulse`;
  await run(sandbox, 'mkdir', ['-p', configDir], { env: SAFE_ENV });
  const config = [
    'enabled: false',
    `repository_path: "${SCRATCH_DIR}"`,
    'remote_branch: "main"',
    'commits_per_day: 2',
    'dry_run: true',
    'push_remote: "origin"',
    '',
  ].join('\n');
  await sandbox.writeFiles([{
    path: `${configDir}/config.yaml`,
    content: Buffer.from(config, 'utf8'),
  }]);

  // The production fast path only needs the compiled binary and fixtures.
  // Remove the source tree and toolchain before snapshotting to keep restores lean.
  await run(sandbox, 'rm', ['-rf', SOURCE_DIR, GO_ROOT], { env: SAFE_ENV });
  await run(sandbox, 'rm', ['-f',
    `/vercel/sandbox/go${GO_VERSION}.linux-amd64.tar.gz`,
    `/vercel/sandbox/go${GO_VERSION}.linux-arm64.tar.gz`,
  ], { env: SAFE_ENV });

  const shaScript = 'const fs=require("fs"),c=require("crypto");process.stdout.write(c.createHash("sha256").update(fs.readFileSync(process.argv[1])).digest("hex"))';
  const binarySha256 = (await run(sandbox, 'node', ['-e', shaScript, GITPULSE_BIN], { env: SAFE_ENV })).trim();

  const marker = {
    schemaVersion: SCHEMA_VERSION,
    sourceCommit: ref,
    binarySha256,
    os: 'linux',
    architecture: (await run(sandbox, 'uname', ['-m'], { env: SAFE_ENV })).trim(),
    createdAt: new Date().toISOString(),
  };
  await sandbox.writeFiles([{
    path: MARKER_PATH,
    content: Buffer.from(JSON.stringify(marker), 'utf8'),
  }]);

  return marker;
}

async function main() {
  const ref = sourceRef();

  if (!process.env.VERCEL_OIDC_TOKEN) {
    await writeColdFallback(ref, 'VERCEL_OIDC_TOKEN unavailable');
    return;
  }

  console.log(`[playground snapshot] preparing GitPulse runtime for ${ref} in ${REGION}`);
  let sandbox;
  let snapshotted = false;
  try {
    sandbox = await Sandbox.create({
      runtime: 'node24',
      persistent: false,
      region: REGION,
      timeout: 240_000,
      env: SAFE_ENV,
      tags: { app: 'gitpulse', purpose: 'playground-runtime-build' },
    });

    const marker = await prepareSnapshot(sandbox, ref);
    const snapshot = await sandbox.snapshot({ expiration: SNAPSHOT_EXPIRATION_MS });
    snapshotted = true;
    const snapshotId = snapshot.snapshotId || snapshot.id;
    if (!snapshotId) throw new Error('Vercel Sandbox returned a snapshot without an ID');

    await writeGenerated({
      schemaVersion: SCHEMA_VERSION,
      snapshotId,
      sourceCommit: marker.sourceCommit,
      binarySha256: marker.binarySha256,
      region: REGION,
    });
    console.log(`[playground snapshot] ready: ${snapshotId}`);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    // Snapshotting is a performance optimization. The public site and the
    // disposable cold playground must remain deployable if that optional
    // build-time service is unavailable.
    await writeColdFallback(ref, `snapshot preparation failed: ${message}`);
  } finally {
    if (sandbox && !snapshotted) {
      try { await sandbox.delete(); } catch {}
    }
  }
}

main().catch((error) => {
  console.error('[playground snapshot] failed:', error);
  process.exit(1);
});
